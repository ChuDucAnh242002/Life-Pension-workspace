CREATE TABLE adviser_case (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision NUMBER(19) NOT NULL,
    status VARCHAR2(20) NOT NULL CHECK (status IN ('DRAFT', 'IN_REVIEW', 'CLOSED')),
    customer_alias VARCHAR2(100 CHAR) NOT NULL,
    age NUMBER(3),
    employment VARCHAR2(30) NOT NULL CHECK (employment IN ('UNKNOWN', 'EMPLOYED', 'SELF_EMPLOYED', 'RETIRED', 'OTHER')),
    dependants NUMBER(2),
    monthly_income NUMBER(14,2),
    pension_contribution NUMBER(14,2),
    life_cover NUMBER(14,2),
    notes VARCHAR2(2000 CHAR),
    updated_at VARCHAR2(35) NOT NULL,
    CHECK (age IS NULL OR age BETWEEN 18 AND 100),
    CHECK (dependants IS NULL OR dependants BETWEEN 0 AND 20),
    CHECK (monthly_income IS NULL OR monthly_income >= 0),
    CHECK (pension_contribution IS NULL OR pension_contribution >= 0),
    CHECK (life_cover IS NULL OR life_cover >= 0)
);
CREATE TABLE case_change (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id NUMBER(19) NOT NULL REFERENCES adviser_case(id),
    revision NUMBER(19) NOT NULL,
    actor VARCHAR2(100 CHAR) NOT NULL,
    action VARCHAR2(40) NOT NULL,
    changed_at VARCHAR2(35) NOT NULL,
    snapshot CLOB NOT NULL,
    UNIQUE(case_id, revision)
);
